"""Optional Godot 4 renderer bridge.

Python remains the controller and input/tray owner.  When a local Godot 4
binary is available, this module launches the generated ``godot_runtime/``
project and pushes compact state packets over a loopback UDP socket.  When no
binary exists (the normal development/test environment), :attr:`available` is
false and the caller keeps using the PyQt renderer unchanged.

No cloud service, model download or non-loopback network access is involved.
"""

from __future__ import annotations

import json
import os
import shutil
import socket
import subprocess
import tempfile
import time
import uuid
from pathlib import Path
from typing import Any

PROJECT_ROOT = Path(__file__).resolve().parents[1]
RUNTIME_DIR = PROJECT_ROOT / "godot_runtime"
STATE_NAME = "deskling_engine_state.json"

PROJECT_GODOT = """\
; Generated by Deskling. Safe to edit; the bridge only ensures it exists.
config_version=5

[application]

config/name="Deskling Godot Renderer"
run/main_scene="res://pet_renderer.tscn"
config/features=PackedStringArray("4.2", "GL Compatibility")

[display]

window/size/viewport_width=360
window/size/viewport_height=540
window/size/resizable=false
window/size/borderless=true
window/size/transparent=true
window/size/always_on_top=true
window/per_pixel_transparency/allowed=true
window/energy_saving/keep_screen_on=false

[rendering]

renderer/rendering_method="gl_compatibility"
renderer/rendering_method.mobile="gl_compatibility"
environment/defaults/default_clear_color=Color(0, 0, 0, 0)
"""


def ensure_runtime() -> Path:
    """Create the tiny Godot project on disk if it is missing."""

    RUNTIME_DIR.mkdir(parents=True, exist_ok=True)
    project = RUNTIME_DIR / "project.godot"
    if not project.is_file():
        project.write_text(PROJECT_GODOT, encoding="utf-8")
    return RUNTIME_DIR


def _free_udp_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
        sock.bind(("127.0.0.1", 0))
        return int(sock.getsockname()[1])


def find_godot(explicit: str | Path | None = None) -> Path | None:
    """Find a local Godot 4 executable; never downloads one."""

    candidates: list[str] = []
    if explicit:
        candidates.append(str(explicit))
    for variable in ("GODOT_BIN", "GODOT4_BIN", "DESKLING_GODOT"):
        value = os.environ.get(variable)
        if value:
            candidates.append(value)
    # The requested conventional drop-in location.
    candidates.extend(
        [
            str(PROJECT_ROOT / "engine" / "godot.exe"),
            str(RUNTIME_DIR / "godot.exe"),
        ]
    )
    for name in ("godot", "godot4", "Godot", "Godot4"):
        found = shutil.which(name)
        if found:
            candidates.append(found)
    for root in (
        Path(os.environ.get("ProgramFiles", r"C:\Program Files")),
        Path(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)")),
        Path(os.environ.get("LOCALAPPDATA", "")) / "Programs",
        Path(r"D:\software"),
        PROJECT_ROOT,
    ):
        if not str(root) or not root.is_dir():
            continue
        try:
            candidates.extend(str(p) for p in root.glob("Godot_v4*"))
            candidates.extend(str(p) for p in root.glob("Godot*"))
        except OSError:
            continue
    for candidate in candidates:
        path = Path(candidate)
        if path.is_file():
            return path
        found = shutil.which(candidate)
        if found:
            return Path(found)
    return None


class GodotBridge:
    """Launch and drive the optional Godot render window via local UDP."""

    def __init__(
        self,
        character_dir: Path | str,
        *,
        godot_bin: str | Path | None = None,
        state_file: Path | str | None = None,
        port: int | None = None,
    ) -> None:
        self.character_dir = Path(character_dir)
        self.godot_bin = find_godot(godot_bin)
        self.port = int(port or _free_udp_port())
        self.state_file = Path(
            state_file
            or (
                Path(tempfile.gettempdir())
                / f"{STATE_NAME}.{os.getpid()}.{uuid.uuid4().hex[:8]}.json"
            )
        )
        self.process: subprocess.Popen[bytes] | None = None
        self._socket: socket.socket | None = None
        self._state: dict[str, Any] = {
            "x": 0,
            "y": 0,
            "width": 288,
            "height": 432,
            "scale": 0.8,
            "state": "idle",
            "pose": "idle",
            "vx": 0.0,
            "quit": False,
        }

    @property
    def available(self) -> bool:
        return self.godot_bin is not None and self.character_dir.is_dir()

    @property
    def running(self) -> bool:
        return self.process is not None and self.process.poll() is None

    @property
    def command(self) -> list[str]:
        if self.godot_bin is None:
            return []
        runtime = ensure_runtime()
        return [
            str(self.godot_bin),
            "--path",
            str(runtime),
            "--",
            "--character",
            str(self.character_dir.resolve()),
            "--state",
            str(self.state_file.resolve()),
            "--port",
            str(self.port),
        ]

    def _open_socket(self) -> socket.socket:
        if self._socket is None:
            self._socket = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        return self._socket

    def _send(self, payload: dict[str, Any]) -> bool:
        try:
            data = json.dumps(payload, ensure_ascii=False).encode("utf-8")
            self._open_socket().sendto(data, ("127.0.0.1", self.port))
            return True
        except OSError:
            return False

    def _write_state(self) -> bool:
        try:
            self.state_file.parent.mkdir(parents=True, exist_ok=True)
            temporary = self.state_file.with_suffix(".tmp")
            payload = json.dumps(self._state, ensure_ascii=False)
            temporary.write_text(payload, encoding="utf-8")
            try:
                temporary.replace(self.state_file)
            except OSError:
                self.state_file.write_text(payload, encoding="utf-8")
            return True
        except OSError:
            return False

    def update(self, **state: Any) -> bool:
        """Publish one frame of state to Godot (file + UDP loopback)."""

        self._state.update(state)
        self._state["quit"] = False
        self._write_state()
        if self.running:
            return self._send(self._state)
        return True

    def start(
        self,
        *,
        width: int = 288,
        height: int = 432,
        x: int = 0,
        y: int = 0,
        scale: float = 0.8,
        offset_x: int = 0,
        offset_y: int = 0,
    ) -> bool:
        if not self.available:
            return False
        if self.running:
            return True
        ensure_runtime()
        self._state.update(
            {
                "x": int(x),
                "y": int(y),
                "width": max(16, int(width)),
                "height": max(16, int(height)),
                "scale": float(scale),
                "offset_x": int(offset_x),
                "offset_y": int(offset_y),
                "quit": False,
            }
        )
        self._write_state()
        try:
            creationflags = getattr(subprocess, "CREATE_NO_WINDOW", 0) if os.name == "nt" else 0
            self.process = subprocess.Popen(
                self.command,
                cwd=str(ensure_runtime()),
                stdin=subprocess.DEVNULL,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                creationflags=creationflags,
            )
        except OSError:
            self.process = None
            return False
        # Give the renderer a moment to bind its UDP socket, then push state.
        time.sleep(0.15)
        self._send(self._state)
        return True

    def stop(self, timeout: float = 2.0) -> None:
        if self.process is not None:
            self._state["quit"] = True
            self._write_state()
            self._send(self._state)
            try:
                self.process.wait(timeout=timeout)
            except (OSError, subprocess.TimeoutExpired):
                try:
                    self.process.terminate()
                    self.process.wait(timeout=timeout)
                except (OSError, subprocess.TimeoutExpired):
                    try:
                        self.process.kill()
                    except OSError:
                        pass
            self.process = None
        if self._socket is not None:
            try:
                self._socket.close()
            except OSError:
                pass
            self._socket = None
        try:
            self.state_file.unlink(missing_ok=True)
        except OSError:
            pass

    def __del__(self) -> None:  # pragma: no cover - best effort
        try:
            self.stop(timeout=0.5)
        except Exception:
            pass


def _main(argv: list[str] | None = None) -> int:
    import argparse
    import sys

    parser = argparse.ArgumentParser(
        description="Launch the optional Godot 4 Deskling renderer"
    )
    parser.add_argument("--character", type=Path, required=True)
    parser.add_argument("--godot", type=Path, default=None)
    parser.add_argument("--width", type=int, default=288)
    parser.add_argument("--height", type=int, default=432)
    parser.add_argument("--x", type=int, default=100)
    parser.add_argument("--y", type=int, default=100)
    parser.add_argument("--duration", type=float, default=0.0)
    args = parser.parse_args(argv)
    bridge = GodotBridge(args.character, godot_bin=args.godot)
    if not bridge.available:
        print(
            "Godot 4 executable not found. Set GODOT_BIN or place godot.exe in "
            "engine/; the normal PyQt renderer remains active.",
            file=sys.stderr,
        )
        return 2
    if not bridge.start(
        width=args.width,
        height=args.height,
        x=args.x,
        y=args.y,
    ):
        print("Failed to launch Godot.", file=sys.stderr)
        return 3
    print(f"Godot renderer launched: pid={bridge.process.pid if bridge.process else '?'}")
    deadline = time.monotonic() + args.duration if args.duration > 0 else None
    try:
        while bridge.running and (deadline is None or time.monotonic() < deadline):
            time.sleep(0.25)
    except KeyboardInterrupt:
        pass
    finally:
        bridge.stop()
    return 0


if __name__ == "__main__":
    raise SystemExit(_main())
